// bitmapFont table. Each glyph is 7 rows of 5 chars ('#' = ink), compiled to
// row bitmasks exactly the way Go's glyph() does: bit (4-col), MSB = leftmost
// column. The agreement tests treat this table and the Go one as one
// contract; never change a side alone.
//
// Why a bitmap font at all: a text annotation must render PIXEL-IDENTICALLY
// in the frame preview and in the Go re-render, and the standard library has
// no font rasterizer (pulling golang.org/x/image/font would add the one new
// dependency this plugin is forbidden to grow). A 5×7 pixel font with
// integer scaling is deterministic by construction — both sides walk the
