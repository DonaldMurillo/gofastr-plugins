export const GLYPH_WIDTH = 5;
export const GLYPH_HEIGHT = 7;
/** Per-character advance in cells: 5 glyph columns + 1 space column. */
export const ADVANCE_CELLS = 6;

// Compiled form: char → 7 row bitmasks, MSB = leftmost column. Mirrors the
// Go table's [7]byte exactly.
const COMPILED: Record<string, number[]> = {};
for (const [ch, rows] of Object.entries(ROWS)) {
  COMPILED[ch] = rows.map((row) =>
    row.split("").reduce((bits, cell) => (bits << 1) | (cell === "#" ? 1 : 0), 0)
  );
}

/** Rows for one character after uppercasing, or null for unknown glyphs. */
export function glyphRows(ch: string): number[] | null {
  const up = ch >= "a" && ch <= "z" ? String.fromCharCode(ch.charCodeAt(0) - 32) : ch;
  return COMPILED[up] ?? null;
}

/** Advance width of a string at integer cell scale, in pixels. */
export function textWidth(s: string, scale: number): number {
  return s.length * ADVANCE_CELLS * scale;
}
